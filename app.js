function completenessTotalFromRows(rows) {
  const itemCount = rows.reduce((sum, row) => sum + (row.itemCount || 0), 0);
  const complete = rows.reduce((sum, row) => sum + (row.complete || 0), 0);
  const needed = rows.reduce((sum, row) => sum + (row.needed || 0), 0);
  const gap = needed - complete;

  return {
    itemCount,
    complete,
    pct: itemCount ? (complete / itemCount) * 100 : 0,
    goal: itemCount ? (needed / itemCount) * 100 : 0,
    needed,
    gap,
  };
}

