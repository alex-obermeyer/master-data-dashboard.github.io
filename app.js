function setupSupplierRows() {
  const selectedMda = $("#setup-supplier-mda").value;
  const sort = $("#setup-supplier-sort").value;
  const goal = setupGoalConfig();
  const rows = setupSupplierData.filter((row) => row.mda === selectedMda);
  const other = rows.find((row) => row.supplier === "All other suppliers");
  const supplierRowsOnly = rows.filter((row) => row.supplier !== "All other suppliers");

  const sorted = supplierRowsOnly.sort((a, b) => {
    if (sort === "not-approved-desc") return b.notApproved - a.notApproved || b.open - a.open;
    if (sort === "metric-desc") return (b[goal.key] || 0) - (a[goal.key] || 0) || b.open - a.open;
    if (sort === "completed-desc") return b.completed - a.completed || b.total - a.total;
    return b.open - a.open || b.notApproved - a.notApproved;
  });

  return other ? [...sorted, other] : sorted;
}

function dayCell(metric, value) {
  if (value === null || value === undefined) {
    return `<span class="muted">No completed non-Dot</span>`;
  }

  if (metric === "ma") {
    return `<span class="chip">${value.toFixed(2)}</span>`;
  }

  const level = setupLevel(metric, value);
  return `<span class="chip ${level.className}">${value.toFixed(2)} ${level.label}</span>`;
}

