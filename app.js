function completenessItemRows() {
  const selectedMda = selectedCompletenessMda();
  const selectedSupplier = $("#item-supplier").value;
  const selectedElement = $("#item-element").value;
  const query = $("#item-search").value.trim().toLowerCase();

  return selectedCompletenessDataset().items.filter((item) => {
    if (item.mda !== selectedMda) return false;
    if (selectedSupplier && item.supplier !== selectedSupplier) return false;
    if (selectedElement && !(item.missing || []).includes(selectedElement)) return false;
    if (!query) return true;
    return [item.dot, item.gtin, item.mfr, item.description, item.supplier]
      .some((value) => String(value || "").toLowerCase().includes(query));
  });
}

