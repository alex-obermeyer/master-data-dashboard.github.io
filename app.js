function overviewMdas() {
  const names = new Map();
  const addName = (name) => {
    const displayName = titleCaseName(String(name || "").trim());
    if (!displayName || displayName === "Unassigned") return;
    names.set(normalizePersonName(displayName), displayName);
  };

  data.completeness.forEach((row) => addName(row.name));
  data.setupMda.forEach((row) => addName(row.name));
  data.severeByMda.forEach((row) => addName(row.name));
  itemRequestData.forEach((row) => addName(row.mda));
  setupSupplierData.forEach((row) => addName(row.mda));
  completenessItemData.forEach((row) => addName(row.mda));
  severeItemData.forEach((row) => addName(row.mda));

  return [...names.values()].sort((a, b) => a.localeCompare(b));
}

