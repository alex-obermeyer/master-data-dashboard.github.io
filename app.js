function normalizePersonName(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function emailNameCandidate(email) {
  return String(email || "")
    .split("@")[0]
    .replace(/[._-]+/g, " ");
}

function mdaMatchesUser(mda, user) {
  if (!user) return false;
  const normalizedMda = normalizePersonName(mda);
  const candidates = [user.fullName, user.displayName, user.email, emailNameCandidate(user.email)].map(normalizePersonName);

  return candidates.includes(normalizedMda);
}

function requestDefaultMda(mdas) {
  const matchedMda = mdas.find((mda) => mdaMatchesUser(mda, requestViewer));
  requestViewerMatchedMda = matchedMda || "";

  if (matchedMda) return matchedMda;
  if (mdas.includes("Alex Obermeyer")) return "Alex Obermeyer";
  return mdas[0] || "";
}

