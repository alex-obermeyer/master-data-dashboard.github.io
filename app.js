function drawTrend(canvasId) {
  const canvas = document.getElementById(canvasId);
  if (!canvas) return;
  const ctx = canvas.getContext("2d");
  const dpr = window.devicePixelRatio || 1;
  const cssWidth = canvas.clientWidth || canvas.width;
  const cssHeight = Math.max(260, cssWidth * 0.42);
  canvas.width = cssWidth * dpr;
  canvas.height = cssHeight * dpr;
  ctx.scale(dpr, dpr);

  const width = cssWidth;
  const height = cssHeight;
  const pad = { top: 22, right: 18, bottom: 42, left: 48 };
  const rows = data.severeWeekly;
  const max = Math.max(...rows.flatMap((row) => [row.items, row.errors])) * 1.1;
  const x = (index) => pad.left + (index / (rows.length - 1)) * (width - pad.left - pad.right);
  const y = (value) => height - pad.bottom - (value / max) * (height - pad.top - pad.bottom);

  ctx.clearRect(0, 0, width, height);
  ctx.fillStyle = "#ffffff";
  ctx.fillRect(0, 0, width, height);

  ctx.strokeStyle = "#e7e1d7";
  ctx.lineWidth = 1;
  ctx.fillStyle = "#66645f";
  ctx.font = "12px Inter, system-ui, sans-serif";
  for (let i = 0; i <= 4; i += 1) {
    const value = (max / 4) * i;
    const yy = y(value);
    ctx.beginPath();
    ctx.moveTo(pad.left, yy);
    ctx.lineTo(width - pad.right, yy);
    ctx.stroke();
    ctx.fillText(number(value), 6, yy + 4);
  }

  drawLine(ctx, rows.map((row, index) => [x(index), y(row.errors)]), "#b42318");
  drawLine(ctx, rows.map((row, index) => [x(index), y(row.items)]), "#2d5b9a");

  rows.forEach((row, index) => {
    if (index % 4 === 0 || index === rows.length - 1) {
      ctx.fillStyle = "#66645f";
      ctx.fillText(row.date, x(index) - 18, height - 14);
    }
  });

  drawLegend(ctx, width - 190, 18, "#b42318", "Total severe errors");
  drawLegend(ctx, width - 190, 40, "#2d5b9a", "Affected items");
}

function drawLine(ctx, points, color) {
  ctx.strokeStyle = color;
  ctx.lineWidth = 3;
  ctx.lineJoin = "round";
  ctx.lineCap = "round";
  ctx.beginPath();
  points.forEach(([x, y], index) => {
    if (index === 0) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
  });
  ctx.stroke();

  ctx.fillStyle = color;
  points.forEach(([x, y], index) => {
    if (index === points.length - 1 || index % 5 === 0) {
      ctx.beginPath();
      ctx.arc(x, y, 4, 0, Math.PI * 2);
      ctx.fill();
    }
  });
}

function drawLegend(ctx, x, y, color, label) {
  ctx.fillStyle = color;
  ctx.fillRect(x, y - 8, 22, 4);
  ctx.fillStyle = "#171717";
  ctx.font = "12px Inter, system-ui, sans-serif";
  ctx.fillText(label, x + 30, y);
}

