function renderCompleteness() {
  const dataset = selectedCompletenessDataset();
  const total = dataset.total;
  $("#completeness-kpis").innerHTML = [
    [dataset.kpiLabel, percent(total.pct), `${percent(total.goal)} target`],
    ["Complete items", number(total.complete), `${number(total.itemCount)} ${dataset.noun}`],
    ["Gap to goal", number(total.gap), `${number(total.needed)} complete ${dataset.noun} needed`],
    ["Goal coverage", `${total.goal ? Math.round((total.pct / total.goal) * 100) : 0}%`, `of the P8 ${dataset.shortNoun} target achieved`],
  ]
    .map((item) => `<article class="kpi"><p class="label">${item[0]}</p><strong>${item[1]}</strong><span>${item[2]}</span></article>`)
    .join("");

  const search = $("#completeness-search").value.trim().toLowerCase();
  const sort = $("#completeness-sort").value;
  let rows = dataset.rows.filter((row) => row.name.toLowerCase().includes(search));

  rows = rows.sort((a, b) => {
    if (sort === "pct-asc") return a.pct - b.pct;
    if (sort === "items-desc") return b.itemCount - a.itemCount;
    return b.gap - a.gap;
  });

  $("#completeness-table").innerHTML = rows
    .map((row) => {
      const hasGoal = typeof row.goal === "number";
      const status = !hasGoal || row.gap <= 0 ? "good" : row.gap > 1000 ? "bad" : "warn";
      const progressBase = hasGoal ? row.goal : 100;
      const width = Math.min(100, (row.pct / progressBase) * 100);
      return `
        <tr>
          <td>${row.name}</td>
          <td class="number">${number(row.complete)} / ${number(row.itemCount)}<br><span class="muted">${percent(row.pct)}</span></td>
          <td class="number">${hasGoal ? percent(row.goal) : "No P8 goal"}</td>
          <td><span class="chip ${status}">${row.gap > 0 ? number(row.gap) : "At goal"}</span></td>
          <td>
            <div class="progress-track"><div class="progress-fill" style="width:${width}%; background:var(--teal)"></div></div>
          </td>
        </tr>
      `;
    })
    .join("");
  renderSupplierBreakdown();
  renderCompletenessItems();
}

function renderSupplierControls() {
  const selector = $("#completeness-mda");
  const current = selector.value;
  const dataset = selectedCompletenessDataset();
  const supplierMdas = new Set(dataset.suppliers.map((supplier) => supplier.mda));
  const itemMdas = new Set(dataset.items.map((item) => item.mda));
  const names = dataset.rows
    .map((row) => row.name.toUpperCase())
    .filter((name) => supplierMdas.has(name) || itemMdas.has(name))
    .sort((a, b) => titleCaseName(a).localeCompare(titleCaseName(b)));

  selector.innerHTML = names
    .map((name) => `<option value="${name}">${titleCaseName(name)}</option>`)
    .join("");
  selector.value = names.includes(current) ? current : names[0];
}

function titleCaseName(value) {
  return value
    .toLowerCase()
    .split(" ")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function selectedCompletenessMda() {
  return $("#completeness-mda")?.value || "";
}

function supplierRows() {
  const selectedMda = selectedCompletenessMda();
  const sort = $("#supplier-sort").value;
  const rows = selectedCompletenessDataset().suppliers.filter((row) => row.mda === selectedMda);

  return rows.sort((a, b) => {
    if (sort === "pct-asc") return a.pct - b.pct || b.items - a.items;
    if (sort === "items-desc") return b.items - a.items;
    return b.incomplete - a.incomplete || b.items - a.items;
  });
}

function renderSupplierBreakdown() {
  if (!selectedCompletenessMda()) return;
  const dataset = selectedCompletenessDataset();
  const rows = supplierRows();
  const selectedMda = selectedCompletenessMda();
  const total = dataset.rows.find((row) => row.name.toUpperCase() === selectedMda);
  const worst = rows[0];
  const topThreeIncomplete = rows.slice(0, 3).reduce((sum, row) => sum + row.incomplete, 0);
  const totalIncomplete = total ? total.itemCount - total.complete : 0;
  const concentration = totalIncomplete > 0 ? (topThreeIncomplete / totalIncomplete) * 100 : 0;

  $("#supplier-table").innerHTML = rows
    .map((row) => {
      return `
        <tr>
          <td>${escapeHtml(row.supplier)}</td>
          <td class="number">${number(row.complete)} / ${number(row.items)}</td>
          <td><span class="chip ${row.incomplete === 0 ? "good" : "bad"}">${number(row.incomplete)}</span></td>
          <td class="number">${percent(row.pct)}</td>
          <td>
            <div class="progress-track"><div class="progress-fill" style="width:${Math.min(100, row.pct)}%; background:var(--teal)"></div></div>
          </td>
        </tr>
      `;
    })
    .join("");

  $("#supplier-focus").innerHTML = `
    <article class="focus-card">
      <p class="label">${titleCaseName(selectedMda)}</p>
      <strong>${total ? percent(total.pct) : "n/a"}</strong>
      <span>${total ? `${number(total.complete)} of ${number(total.itemCount)} ${dataset.noun} complete` : "No matching MDA total"}</span>
    </article>
    <article class="focus-card">
      <p class="label">Largest supplier gap</p>
      <strong>${worst ? worst.supplier : "n/a"}</strong>
      <span>${worst ? `${number(worst.incomplete)} incomplete ${dataset.noun} at ${percent(worst.pct)} complete` : "No supplier rows"}</span>
    </article>
    <article class="focus-card">
      <p class="label">Top 3 concentration</p>
      <strong>${percent(concentration)}</strong>
      <span>Share of selected MDA incomplete ${dataset.noun} from the top three suppliers in the current sort</span>
    </article>
  `;
}

