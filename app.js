function chipClass(value, goodWhenNegative = false) {
  if (value === 0) return "chip";
  const good = goodWhenNegative ? value < 0 : value > 0;
  return `chip ${good ? "good" : "bad"}`;
}

function parseDate(value) {
  if (!value) return null;
  const date = new Date(`${value}T00:00:00`);
  return Number.isNaN(date.getTime()) ? null : date;
}

function formatDate(value) {
  const date = parseDate(value);
  if (!date) return "-";
  return date.toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
}

function daysBetween(start, end) {
  if (!start || !end) return null;
  return Math.round((end.getTime() - start.getTime()) / 86400000);
}

function setupLevel(metric, value) {
  const level = setupLevels.find((candidate) => value <= candidate[metric]);
  if (!level) {
    return { label: "Above L1", className: "bad", threshold: setupLevels[setupLevels.length - 1][metric] };
  }

  const className = level.label === "L5" || level.label === "L4" ? "good" : level.label === "L3" ? "ok" : "warn";
  return { label: level.label, className, threshold: level[metric] };
}

function levelBadge(metric, value) {
  const level = setupLevel(metric, value);
  return `<span class="chip ${level.className}">${level.label}</span>`;
}

