function renderOverviewRequests(requests) {
  const mdaNeeded = requests
    .filter((item) => !item.mdaCompletionDate)
    .sort((a, b) => {
      const targetDelta = (parseDate(a.targetDate)?.getTime() || Infinity) - (parseDate(b.targetDate)?.getTime() || Infinity);
      return targetDelta || (b.workdaysOpen || 0) - (a.workdaysOpen || 0);
    });

  const duePressure = mdaNeeded.filter((item) => ["overdue", "today", "soon"].includes(requestDueBucket(item))).length;
  const typeCounts = mdaNeeded.reduce((counts, item) => {
    counts[item.requestType] = (counts[item.requestType] || 0) + 1;
    return counts;
  }, {});
  const typeSummary = Object.entries(typeCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([type, count]) => `${escapeHtml(type)}: ${number(count)}`)
    .join(" | ");

  $("#overview-request-summary").innerHTML = `
    <span><strong>${number(mdaNeeded.length)}</strong> need MDA complete</span>
    <span><strong>${number(duePressure)}</strong> due pressure</span>
    <span>${typeSummary || "No request type counts"}</span>
  `;

  if (!mdaNeeded.length) {
    $("#overview-request-table").innerHTML = overviewEmptyRow(6, "No item requests need MDA completion for this MDA.");
    return;
  }

  $("#overview-request-table").innerHTML = mdaNeeded
    .map(
      (item) => `
        <tr>
          <td class="number">
            ${escapeHtml(item.id || "-")}
            <br><span class="muted">${escapeHtml(item.requestType || "-")} ${escapeHtml(item.dotType || "")}</span>
          </td>
          <td>
            <span class="chip ${requestStageClass(item.stage)}">${escapeHtml(item.stage)}</span>
            <br><span class="muted">${escapeHtml(item.status)}</span>
          </td>
          <td>${escapeHtml(item.supplier)}</td>
          <td>
            ${escapeHtml(item.description)}
            <br><span class="muted">GTIN ${escapeHtml(item.gtin || "-")} | Mfr ${escapeHtml(item.manufacturerNumber || "-")}</span>
          </td>
          <td>
            ${requestDueLabel(item)}
            <br><span class="muted">Requested ${formatDate(item.requestedDate)} | Target ${formatDate(item.targetDate)}</span>
            <div class="completion-flags">${requestCompletionFlag("MDA", item.mdaCompletionDate)}</div>
          </td>
          <td class="number">${item.workdaysOpen === null || item.workdaysOpen === undefined ? "-" : number(item.workdaysOpen)}</td>
        </tr>
      `,
    )
    .join("");
}

