function renderOverviewSevere(selectedMda) {
  const rows = rowsForMda(severeItemData, selectedMda);
  if (!rows.length) {
    $("#overview-severe-list").innerHTML = `
      <article class="focus-card">
        <p class="label">Severe errors</p>
        <strong>No item-level errors</strong>
        <span>No severe-error item detail is listed for this MDA in the current export.</span>
      </article>
    `;
    return;
  }

  const typeCounts = rows.reduce((counts, item) => {
    (item.errors || []).forEach((error) => {
      counts[error.type] = (counts[error.type] || 0) + 1;
    });
    return counts;
  }, {});
  const totalErrors = Object.values(typeCounts).reduce((sum, count) => sum + count, 0);
  const topSupplier = Object.entries(
    rows.reduce((counts, item) => {
      counts[item.supplier] = (counts[item.supplier] || 0) + item.totalErrors;
      return counts;
    }, {}),
  ).sort((a, b) => b[1] - a[1])[0];

  $("#overview-severe-list").innerHTML = `
    <article class="focus-card">
      <p class="label">Top supplier</p>
      <strong>${escapeHtml(topSupplier?.[0] || "n/a")}</strong>
      <span>${topSupplier ? `${number(topSupplier[1])} severe errors` : "No supplier concentration"}</span>
    </article>
    ${Object.entries(typeCounts)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 6)
      .map(([type, count]) => {
        const pct = totalErrors ? (count / totalErrors) * 100 : 0;
        return `
          <div class="stack-row">
            <header><span>${escapeHtml(type)}</span><span>${number(count)}</span></header>
            <div class="stack-track"><div class="stack-fill" style="width:${pct}%; background:var(--red)"></div></div>
          </div>
        `;
      })
      .join("")}
  `;
}

